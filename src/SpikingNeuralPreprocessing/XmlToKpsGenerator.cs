using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml.Linq;

namespace SpikingNeuralPreprocessing
{
    internal class XmlToKpsGenerator
    {
        public void Generate(string xmlFilePath, string destinationKpltPath)
        {
            if (!File.Exists(xmlFilePath))
            {
                Console.WriteLine($"Error: XML file not found at {xmlFilePath}");
                return;
            }

            try
            {
                XDocument xmlDoc = XDocument.Load(xmlFilePath);
                TransformXmlToKps(destinationKpltPath, xmlDoc);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error generating .kplt file: {ex.Message}");
            }
        }

        public void TransformXmlToKps(string destinationKpltPath, XDocument xmlDoc)
        {
            StringBuilder sb = new StringBuilder();

            sb.AppendLine("// Automatically generated by the SNP to kPWorkbench Bridge");
            sb.AppendLine();

            // 1. GENERATE CONSTANTS
            var constantsNode = xmlDoc.Root.Element("constants");
            if (constantsNode != null)
            {
                var constants = constantsNode.Elements("constant")
                    .Select(c => $"{c.Attribute("name").Value} = {c.Attribute("value").Value}");

                if (constants.Any())
                {
                    // Outputs: #define n = 2, k = 3
                    sb.AppendLine($"#define {string.Join(", ", constants)}");
                    sb.AppendLine();
                }
            }

            // 2. GENERATE COMPARTMENT TYPES AND RULES
            var typesNode = xmlDoc.Root.Element("compartmentTypes");
            if (typesNode != null)
            {
                foreach (var typeElem in typesNode.Elements("type"))
                {
                    string typeId = typeElem.Attribute("id").Value;
                    bool hasRules = typeElem.Elements("strategy").Elements("rule").Any();
                    if (!hasRules)
                    {
                        sb.AppendLine($"type {typeId} {{}}");
                        sb.AppendLine();
                    }
                    else
                    {
                        sb.AppendLine($"type {typeId} {{");
                        foreach (var strategyElem in typeElem.Elements("strategy"))
                        {
                            string strategyType = strategyElem.Attribute("type")?.Value ?? "choice";
                            sb.AppendLine($"    {strategyType} {{");

                            foreach (var ruleElem in strategyElem.Elements("rule"))
                            {
                                string guard = ruleElem.Attribute("guard")?.Value;
                                string lhs = ruleElem.Attribute("lhs").Value;
                                string rhs = ruleElem.Attribute("rhs").Value;
                                string loop = ruleElem.Attribute("loop")?.Value;

                                string ruleText = "";

                                if (!string.IsNullOrEmpty(guard))
                                {
                                    ruleText += $"{guard} : ";
                                }

                                // CHANGED: If rhs is empty, format as "lhs -> .", otherwise "lhs -> rhs ."
                                if (string.IsNullOrEmpty(rhs))
                                {
                                    ruleText += $"{lhs} -> .";
                                }
                                else
                                {
                                    ruleText += $"{lhs} -> {rhs} .";
                                }

                                if (!string.IsNullOrEmpty(loop))
                                {
                                    ruleText += $" : {loop}";
                                }

                                sb.AppendLine($"        {ruleText}");
                            }

                            sb.AppendLine("    }");
                        }
                        sb.AppendLine("}");
                        sb.AppendLine();
                    }
                }
            }

            // 3. GENERATE COMPARTMENT INSTANCES
            var compartmentsNode = xmlDoc.Root.Element("compartments");
            if (compartmentsNode != null)
            {
                foreach (var compElem in compartmentsNode.Elements("compartment"))
                {
                    string id = SanitizeId(compElem.Attribute("id").Value);
                    string type = compElem.Attribute("type").Value;
                    string initMultiset = compElem.Attribute("initialMultiset")?.Value ?? "";
                    string loop = compElem.Attribute("loop")?.Value;

                    // Outputs: c2$i$ {x$i$} (t2) .
                    string compText = $"{id} {{{initMultiset}}} ({type}) .";

                    if (!string.IsNullOrEmpty(loop))
                    {
                        compText += $" : {loop}";
                    }
                    sb.AppendLine(compText);
                }
                sb.AppendLine();
            }

            // 4. GENERATE LINKS
            var linksNode = xmlDoc.Root.Element("links");
            if (linksNode != null)
            {
                foreach (var linkElem in linksNode.Elements("link"))
                {
                    string source = SanitizeId(linkElem.Attribute("source").Value);
                    string target = SanitizeId(linkElem.Attribute("target").Value);
                    string loop = linkElem.Attribute("loop")?.Value;

                    // Outputs: c1 - c2$i$ . 
                    string linkText = $"{source} - {target} .";

                    if (!string.IsNullOrEmpty(loop))
                    {
                        linkText += $" : {loop}";
                    }
                    sb.AppendLine(linkText);
                }
            }

            File.WriteAllText(destinationKpltPath, sb.ToString());
            Console.WriteLine($"Successfully generated kPWorkbench file at: {destinationKpltPath}");
        }
        private string SanitizeId(string id)
        {
            if (string.IsNullOrEmpty(id)) return id;

            // If the first character is a digit, prepend 'c'
            if (char.IsDigit(id[0]))
            {
                return "c" + id;
            }
            return id;
        }
    }
}
